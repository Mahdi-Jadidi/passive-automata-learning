    s,sc,c,w,r,l=core_case(multi); check(r['structural_optimum']==2,'multi-epoch optimum')
    save('core-multi.json',core_json(dict(raw=multi,scope=sc,closure=c,structural=[w],ledger=l.records)))
    # Producer-generated PARTIAL records at 100 different interruption budgets.
    partial=complete=0
    for cap in range(100):
        _,_,cp,_,rp,_=core_case(multi,Budget(work=cap),0)
        if cp['state']=='PARTIAL':partial+=1
        else:complete+=1
    for raw in [dict(alphabet=['β','😀','unused'],positive=[[],['β','😀'],['β','😀']],negative=[['😀','β'],['😀','β']]),dict(alphabet=['a'],positive=[[]],negative=[[]]),dict(alphabet=[],positive=[],negative=[[]]),dict(alphabet=[],positive=[[]],negative=[]),dict(alphabet=['a','unused'],positive=[],negative=[[]])]:core_case(raw)
    print(f'actual_budget_roundtrips=100 partial={partial} fixpoint={complete} extra_degenerate_unicode=5')
    mutations=0
    # Mutate the actual emitted closure, not a handcrafted certificate.
    for key,val in [('epoch',1),('owner',[0,0,2,3]),('result_owner',[0,1,2,3]),('facts',[]),('edges',[])]:
        bad=copy.deepcopy(c);bad['records'][0]['payload'][key]=val;reject(lambda:rr(multi,sc,bad,[w]));mutations+=1
    bad=copy.deepcopy(c);bad['records'][0]['origin']='EXTERNAL';reject(lambda:rr(multi,sc,bad,[w]));mutations+=1
    bad=copy.deepcopy(c);bad['records'].pop();reject(lambda:rr(multi,sc,bad,[w]));mutations+=1
    # False exhaustion from a REAL zero-budget producer result.
    cp=component_closure(s,Budget(work=0)); bad=copy.deepcopy(cp);bad['state']='FIXPOINT';bad['records'][0]['payload'].update(state='EXHAUSTED',cursor=None)
    weak=EvidenceLedger(s);check(weak.append(bad['records']),'expected metadata-only producer gap changed');reject(lambda:rr(multi,sc,bad,[]));mutations+=1
    save('false-exhaustion.json',core_json(dict(raw=multi,scope=sc,actual_partial=cp,mutated=bad)))
    # Actual core atomic rollback: first record valid, later corrupted record invalid.
    atomic=EvidenceLedger(s);bad=copy.deepcopy(c['records'][1]);bad['payload']['epoch']=99
    check(not atomic.append([c['records'][0],bad]) and not atomic.records and atomic.owner==tuple(range(4)),'core partial append')
