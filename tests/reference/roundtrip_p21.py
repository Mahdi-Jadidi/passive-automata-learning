    # Core schema cannot bind expected origin by itself; test the actual divergent admission.
    flip=EvidenceLedger(s); altered=copy.deepcopy(o);altered['origin']='EXTERNAL';altered['payload']['receipt_digest']='f'*64
    check(flip.append([rq,altered]),'core origin gap changed'); check(lr(raw,sc,flip)['operational_status']=='INCOMPLETE','origin flip operational')
    check(canonical(o)!=canonical(altered),'provenance mutation not distinct')
