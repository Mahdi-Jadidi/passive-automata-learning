    print('core_rollback_preserves_pending=PASS structural_no=3 operational_status=INCOMPLETE shared_authoritative_transaction=ABSENT')
    artifact=dict(raw=raw,scope=sc,closure=c,structural=w,committed_adapter_bundles_hex=[b.hex() for b in adapter.records],quarantine_hex=[b.hex() for b in adapter.quarantine],registered_expected=[v for v in registrations.values()],core_ledger=ledger.records,translated=translated,unknown=unknown,core_quarantine=[list(x[:2]) for x in ledger.quarantine])
    print('adapter_artifact_sha256='+save('adapter-roundtrip.json',core_json(artifact)))


