    unknown=dict(version='selector-v2/1',origin='SIMULATOR',sample_digest=sc['sample_digest'],kind='OBSERVATION',payload=dict(request_digest=digest(u),status='UNKNOWN',response_digest=quarantine['wire_sha256'],receipt_digest=None,feedback=None))
    check(ledger.append([ur,unknown]),'UNKNOWN journal translation')
    retry,rt=register([0,1,2],'r-unknown','a-u2');accept(retry,rt,payload(retry,'PROJECTION_NO',failed=0,tables=tables()))
    # Mock ACCEPT with complete finite-language DFA accepting exactly ab and arbitrary unused projection.
    q2,r2=register([0,0,2],'r-accept','a-accept','EXTERNAL')
    d0=dict(block=0,states=4,initial=0,accepting=[2],transitions=[[i,a,{(0,0):1,(1,1):2}.get((i,a),3)] for i in range(4) for a in (0,1)])
    d2=dict(block=2,states=1,initial=0,accepting=[0],transitions=[[0,2,0]])
    b2,o2=accept(q2,r2,payload(q2,'ACCEPT','EXTERNAL','mock-receipt-1',dfas=[d0,d2],joint_row=[[1,1,1],[0,0,0]]))
    q3,r3=register([0,0,2],'r-bounded','a-bounded','EXTERNAL',[1,1]);accept(q3,r3,payload(q3,'BOUNDED_NO','EXTERNAL','mock-receipt-2',exact=True))
