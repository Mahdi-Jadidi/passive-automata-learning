    result=lr(raw,sc,ledger);check(result['operational_status']=='INCOMPLETE' and digest(u) in result['pending_attempt_digests'] and len(result['structural_no_request_digests'])==3,'unsafe replay outcome')
    # Mutate actual committed adapter bytes and verify independently, even with coherent wire rehash.
    reg=registrations['r-no','a-no']; bm=json.loads(b); corrupted=0
    for k,v in [('wire_sha256','0'*64),('wire_hex','ff')]:
        z=copy.deepcopy(bm);z[k]=v;reject(lambda:replay_bundle(raw,canonical(z),reg));corrupted+=1
