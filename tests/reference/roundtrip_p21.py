    check(lr(multi,sc,atomic)['structural_optimum']==2,'rollback replay')
    print(f'actual_closure_mutations_rejected={mutations} false_exhaustion=CORE_ACCEPTED_REPLAY_REJECTED core_atomic_rollback=PASS')
    # Real adapter inputs: deliberately synthetic normalized service responses.
    raw=dict(alphabet=['a','b','unused'],positive=[['a','b'],['a','b']],negative=[['b','a'],[],[]]); s,sc,c,w,_,ledger=core_case(raw)
    adapter=RegisteredLedger(raw,authenticate=lambda q,p:True) # mock seam, NEVER actual trust
    bundles=[]; translated=[]; registrations={}; count=0
    def register(owner,rid,aid,origin='SIMULATOR',caps=None):
        pm=[[f'p{i}',i] for i in range(2)];nm=[[f'n{i}',i] for i in range(3)]
        q=adapter.register(owner,rid,aid,capacities=caps,origin=origin,positive_map=pm,negative_map=nm)
