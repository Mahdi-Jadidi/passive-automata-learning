def check(ok,msg):
    if not ok: raise RuntimeError(msg)


def check_blobs(path,expected):
    for f,wanted in expected.items():
        b=(path/f).read_bytes(); got=hashlib.sha1(b'blob '+str(len(b)).encode()+b'\0'+b).hexdigest()
        check(got==wanted,f'{f}: mismatched Git blob {got}')
        print(f'blob {f} {got}')


def reject(fn):
    try: fn()
    except (InvalidProof,ValueError): return
    raise RuntimeError('unexpectedly accepted mutation')


def main(core_dir,interface_dir,out):
    check_blobs(core_dir/'selector_v2',CORE_BLOBS);check_blobs(interface_dir,INTERFACE_BLOBS)
    sys.path[:0]=[str(core_dir),str(interface_dir)]
    # Imports are in the driver ONLY. Independent kernels never import producer code.
    from selector_v2.core import Sample,PartitionRef,Budget
